from textwrap import dedent
def build_script(topic):
    examples='\n'.join(f'مثال {i}: {x}' for i,x in enumerate(topic['examples'],1))
    return dedent(f'''{topic['hook']}

در این ویدئو قرار است {topic['lesson']}

اول، مسئله را دقیق تعریف می‌کنیم. وقتی هدف مشخص نباشد، حتی بهترین ابزار هوش مصنوعی هم ممکن است خروجی نامناسبی بدهد.

{examples}

حالا این روش را به یک روند ساده تبدیل کنیم. اول هدف را در یک جمله بنویسید. بعد اطلاعات زمینه‌ای موردنیاز را اضافه کنید. سپس محدودیت‌ها و قالب خروجی را مشخص کنید. در پایان، پاسخ را بررسی کنید و اگر لازم بود سؤال را دقیق‌تر کنید.

یک نکته مهم: هوش مصنوعی جای بررسی انسانی را نمی‌گیرد. مخصوصاً برای اطلاعات مهم، نتیجه را با منبع معتبر کنترل کنید.

اگر این آموزش برایتان مفید بود، موضوع بعدی را از همین مجموعه دنبال کنید.''').strip()
def make_title(topic): return topic['title']+' | آموزش کاربردی AI'
def make_description(topic): return 'در این ویدئو: '+topic['title']+'\n\n'+topic['lesson']+'\n\nاین ویدئو برای آموزش کاربردی و مسئولانه ابزارهای هوش مصنوعی تهیه شده است.\n\n'+' '.join('#'+x.replace(' ','_') for x in topic['tags'])
